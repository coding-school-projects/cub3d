#include "libft.h"

size_t	ft_strlcpy(char *dst, const char *src, size_t size)
{
	size_t	i;

	i = 0;
	if (size > 0)
	{
		while (src[i] && i < (size - 1))
		{
			dst[i] = src[i];
			i++;
		}
		dst[i] = 0;
	}
	while (src[i])
		i++;
	return (i);
}

void	ft_strcpy(char *dest, char *src)
{
	if (!dest || !src)
		return ;
	while (*src)
		*dest++ = *src++;
	*dest = 0;
}
